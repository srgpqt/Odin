#!/usr/bin/env python3
"""
Regenerates the source manifests used by the Odin compiler's bundled libc
support (see src/cross_libc.cpp) from a Zig source checkout.

    python3 libc/tools/update_from_zig.py <path-to-zig> [<path-to-musl-1.2.5>]

The libc sources themselves (glibc start files and abilists, musl, mingw-w64,
the FreeBSD/NetBSD start files and abilists, Darwin's libSystem.tbd and the
headers needed to compile them) are copied verbatim from `<zig>/lib/libc`.

Zig implements a handful of musl's functions in Zig (`lib/c` and
`lib/compiler_rt`) and deletes the C originals. Odin has nothing to replace
them with, so those files are restored from the matching upstream musl release
when its path is given.
"""
import os, re, shutil, sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))

ARCHES = ("i386", "x86_64", "aarch64", "arm", "riscv64")
MUSL_ARCH_DIRS = (
    "aarch64", "arm", "generic", "hexagon", "i386", "loongarch64", "m68k", "microblaze",
    "mips", "mips64", "mipsn32", "or1k", "powerpc", "powerpc64", "riscv32", "riscv64",
    "s390x", "sh", "x32", "x86_64",
)
# Directories whose missing files are restored from upstream musl.
MUSL_RESTORE_DIRS = ("math", "stdlib", "string")

def zig_array(text, name):
    m = re.search(r"const %s = \[_\]\[\]const u8\{(.*?)\n\};" % re.escape(name), text, re.S)
    if not m:
        raise SystemExit("could not find array '%s'" % name)
    out = []
    for line in m.group(1).splitlines():
        line = line.split("//")[0].strip().rstrip(",")
        if not line:
            continue
        parts = re.findall(r'"([^"]*)"|path\.sep_str', line)
        # `"a" ++ path.sep_str ++ "b"` => a/b
        path = "".join(p if p else "/" for p in parts)
        out.append(path)
    return out

def musl(zig, upstream):
    text = open(os.path.join(zig, "src/libs/musl.zig")).read()
    src = [p for p in zig_array(text, "src_files") if "/malloc/oldmalloc/" not in p]
    time32 = zig_array(text, "compat_time32_files")

    restored = []
    if upstream:
        for d in MUSL_RESTORE_DIRS:
            for base, _, files in os.walk(os.path.join(upstream, "src", d)):
                for f in sorted(files):
                    if not f.endswith((".c", ".s", ".S")):
                        continue
                    full = os.path.join(base, f)
                    rel  = os.path.relpath(full, upstream).replace(os.sep, "/")
                    arch = rel.split("/")[2] if rel.count("/") == 3 else None
                    if arch is not None and arch not in ARCHES:
                        continue
                    dst = os.path.join(ROOT, "musl", rel)
                    if "musl/" + rel in src:
                        continue
                    os.makedirs(os.path.dirname(dst), exist_ok=True)
                    shutil.copyfile(full, dst)
                    restored.append("musl/" + rel)
    else:
        # Keep whatever has been restored previously.
        old = os.path.join(ROOT, "musl", "sources.txt")
        if os.path.exists(old):
            section = None
            for line in open(old):
                line = line.strip()
                if line.startswith("["):
                    section = line
                elif line and section == "[restored]":
                    restored.append(line)

    with open(os.path.join(ROOT, "musl", "sources.txt"), "w") as f:
        f.write("# Generated by libc/tools/update_from_zig.py, do not edit.\n")
        f.write("[src]\n" + "\n".join(sorted(src)) + "\n")
        f.write("[restored]\n" + "\n".join(sorted(restored)) + "\n")
        f.write("[time32]\n" + "\n".join(sorted(time32)) + "\n")

def mingw(zig):
    text = open(os.path.join(zig, "src/libs/mingw.zig")).read()
    sections = (
        ("generic",     "mingw32_generic_src"),
        ("x86",         "mingw32_x86_src"),
        ("x86_32",      "mingw32_x86_32_src"),
        ("arm",         "mingw32_arm_src"),
        ("arm32",       "mingw32_arm32_src"),
        ("arm64",       "mingw32_arm64_src"),
        ("winpthreads", "mingw32_winpthreads_src"),
        ("always_link", "always_link_libs"),
    )
    with open(os.path.join(ROOT, "mingw", "sources.txt"), "w") as f:
        f.write("# Generated by libc/tools/update_from_zig.py, do not edit.\n")
        for section, name in sections:
            f.write("[%s]\n" % section + "\n".join(zig_array(text, name)) + "\n")

def main():
    if len(sys.argv) < 2:
        raise SystemExit(__doc__)
    zig = sys.argv[1]
    upstream = sys.argv[2] if len(sys.argv) > 2 else None
    musl(zig, upstream)
    mingw(zig)

if __name__ == "__main__":
    main()
