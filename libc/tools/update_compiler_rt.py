#!/usr/bin/env python3
"""
Copies the "builtins" of LLVM's compiler-rt into `libc/compiler_rt` and
generates the list of sources the Odin compiler builds for each target
(see `cross_build_compiler_rt` in src/cross_libc.cpp).

    python3 libc/tools/update_compiler_rt.py <path-to-compiler-rt-source>

The source can be the `compiler-rt-<version>.src.tar.xz` of any LLVM release.
"""
import os, re, shutil, sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))

KEEP_DIRS = ("aarch64", "arm", "i386", "riscv", "x86_64")

# Things which need a hosted environment (headers of the libc, an unwinder, ...)
# and which nothing that Odin generates relies on.
EXCLUDE = {
    "apple_versioning.c", "atomic.c", "clear_cache.c", "emutls.c", "enable_execute_stack.c",
    "eprintf.c", "gcc_personality_v0.c", "os_version_check.c", "trampoline_setup.c",
}

def cmake_list(text, name):
    m = re.search(r"^set\(%s\n(.*?)^\)" % re.escape(name), text, re.S | re.M)
    if not m:
        raise SystemExit("could not find the list '%s'" % name)
    out = []
    for line in m.group(1).splitlines():
        line = line.split("#")[0].strip()
        if line and not line.startswith("$"):
            out.append(line)
    return out

def main():
    if len(sys.argv) != 2:
        raise SystemExit(__doc__)
    src = os.path.join(sys.argv[1], "lib", "builtins")
    dst = os.path.join(ROOT, "compiler_rt", "builtins")
    # NOTE: `libc/compiler_rt/odin` is not a part of compiler-rt and is left alone
    if os.path.exists(dst):
        shutil.rmtree(dst)
    os.makedirs(dst)

    for name in sorted(os.listdir(src)):
        full = os.path.join(src, name)
        if os.path.isdir(full):
            if name in KEEP_DIRS:
                shutil.copytree(full, os.path.join(dst, name))
        elif name.endswith((".c", ".h", ".inc", ".S")):
            shutil.copyfile(full, os.path.join(dst, name))
    shutil.copyfile(os.path.join(sys.argv[1], "LICENSE.TXT"), os.path.join(ROOT, "compiler_rt", "LICENSE.TXT"))

    text = open(os.path.join(src, "CMakeLists.txt")).read()
    generic = [s for s in cmake_list(text, "GENERIC_SOURCES") if s not in EXCLUDE]
    tf      = cmake_list(text, "GENERIC_TF_SOURCES")
    x86_80  = cmake_list(text, "x86_80_BIT_SOURCES")
    arm     = [s for s in cmake_list(text, "arm_or_thumb2_base_SOURCES")] + \
              cmake_list(text, "arm_sync_SOURCES") + \
              cmake_list(text, "arm_EABI_RT_SOURCES")

    i386_asm = [
        "ashldi3", "ashrdi3", "divdi3", "floatdidf", "floatdisf", "floatundidf", "floatundisf",
        "lshrdi3", "moddi3", "muldi3", "udivdi3", "umoddi3", "floatdixf", "floatundixf",
    ]

    sections = [
        ("generic", generic),

        ("x86_64", tf + x86_80 + ["i386/fp_mode.c", "x86_64/floatdidf.c", "x86_64/floatdisf.c", "x86_64/floatdixf.c"]),
        ("x86_64-unix", ["x86_64/floatundidf.S", "x86_64/floatundisf.S", "x86_64/floatundixf.S"]),
        ("x86_64-windows", ["x86_64/chkstk.S", "../odin/windows_msvc_compat.c"]),

        ("i386", x86_80 + ["i386/fp_mode.c"] + ["i386/%s.S" % s for s in i386_asm]),
        ("i386-unix", []),
        ("i386-windows", ["i386/chkstk.S", "../odin/windows_msvc_compat.c"]),

        ("aarch64", tf + ["aarch64/fp_mode.c"]),
        ("arm", arm),
        ("riscv64", tf + ["riscv/fp_mode.c", "riscv/save.S", "riscv/restore.S", "riscv/muldi3.S"]),
    ]

    with open(os.path.join(ROOT, "compiler_rt", "sources.txt"), "w") as f:
        f.write("# Generated by libc/tools/update_compiler_rt.py, do not edit.\n")
        for name, sources in sections:
            for s in sources:
                if not os.path.exists(os.path.join(dst, s)):
                    raise SystemExit("missing source '%s'" % s)
            f.write("[%s]\n" % name)
            if sources:
                f.write("\n".join(sources) + "\n")

if __name__ == "__main__":
    main()
